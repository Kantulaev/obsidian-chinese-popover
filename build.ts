// @ts-nocheck: build script uses dynamic Deno APIs not in typedefs
import * as esbuild from "esbuild";

declare const Deno: {
  args: string[];
  mkdir(path: string, options?: { recursive?: boolean }): Promise<void>;
  copyFile(from: string, to: string): Promise<void>;
  exit(code?: number): void;
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Obsidian Chinese Popover Dictionary (Pinyin + Jyutping + Cantonese Voice)
*/
`;

const prod = Deno.args.includes("production") || !Deno.args.includes("dev");

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: false,
  treeShaking: true,
  outfile: "main.js",
  minify: true,
});

async function copyToDist() {
  const distDir = "./dist/chinese-popover-dict";
  await Deno.mkdir(distDir, { recursive: true });

  const filesToCopy = ["manifest.json", "main.js", "styles.css", "cedict.json"];

  for (const file of filesToCopy) {
    try {
      await Deno.copyFile(file, `${distDir}/${file}`);
    } catch (e: unknown) {
      const err = e instanceof Error ? e.message : String(e);
      console.warn(`Could not copy ${file}:`, err);
    }
  }

  try {
    await Deno.mkdir(`${distDir}/dicts`, { recursive: true });
    for await (const entry of Deno.readDir("dicts")) {
      if (entry.isFile && entry.name.endsWith(".json")) {
        await Deno.copyFile(`dicts/${entry.name}`, `${distDir}/dicts/${entry.name}`);
      }
    }
  } catch (_e) {
    // optional
  }

  console.log("=================================================");
  console.log("SUCCESS! Distribution package ready in:");
  console.log("   ./dist/chinese-popover-dict/");
  console.log("Files copied:");
  console.log("   - manifest.json");
  console.log("   - main.js");
  console.log("   - styles.css");
  console.log("   - cedict.json");
  console.log("=================================================");
}

if (prod) {
  await context.rebuild();
  await context.dispose();
  await copyToDist();
  await esbuild.stop();
  Deno.exit(0);
} else {
  console.log("Watching for changes in dev mode...");
  await context.watch();
}
