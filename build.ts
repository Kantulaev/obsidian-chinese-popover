import * as esbuild from "npm:esbuild@^0.25.0";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Obsidian Chinese Popover Dictionary (Pinyin + Jyutping + Cantonese Voice)
*/
`;

const prod = Deno.args.includes("production") || !Deno.args.includes("dev");

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: false,
  treeShaking: true,
  outfile: "main.js",
  minify: true,
});

async function copyToDist() {
  const distDir = "./dist/obsidian-chinese-popover";
  await Deno.mkdir(distDir, { recursive: true });

  const filesToCopy = ["manifest.json", "main.js", "styles.css", "cedict.json"];

  for (const file of filesToCopy) {
    try {
      await Deno.copyFile(file, `${distDir}/${file}`);
    } catch (e) {
      console.warn(`Could not copy ${file}:`, e.message);
    }
  }

  console.log("=================================================");
  console.log("SUCCESS! Distribution package ready in:");
  console.log("   ./dist/obsidian-chinese-popover/");
  console.log("Files copied:");
  console.log("   - manifest.json");
  console.log("   - main.js");
  console.log("   - styles.css");
  console.log("   - cedict.json");
  console.log("=================================================");
}

if (prod) {
  await context.rebuild();
  await context.dispose();
  await copyToDist();
  Deno.exit(0);
} else {
  console.log("Watching for changes in dev mode...");
  await context.watch();
}
