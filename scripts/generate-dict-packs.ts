for (const pack of PACK_DEFS) {
  const result: Record<string, string[]> = {};

  // 1. Add core vocabulary
  for (const [chWord, langs] of Object.entries(MULTILANG_CORE_VOCAB)) {
    const defs = langs[pack.id];
    if (defs && defs.length > 0) {
      result[chWord] = [...defs];
    }
  }

  // 2. Add extended vocabulary
  for (const [chWord, langs] of Object.entries(EXTENDED_VOCAB)) {
    const defs = langs[pack.id];
    if (defs && defs.length > 0) {
      if (!result[chWord]) {
        result[chWord] = [...defs];
      } else {
        for (const d of defs) {
          if (!result[chWord].includes(d)) {
            result[chWord].push(d);
          }
        }
      }
    }
  }

  // 3. For Russian, merge with RUSSIAN_TRANSLATIONS
  if (pack.id === "ru") {
    for (const [chWord, defs] of Object.entries(RUSSIAN_TRANSLATIONS)) {
      if (!result[chWord]) {
        result[chWord] = [...defs];
      } else {
        for (const d of defs) {
          if (!result[chWord].includes(d)) {
            result[chWord].push(d);
          }
        }
      }
    }
  }

  const outPath = `./dicts/${pack.fileName}`;
  await Deno.writeTextFile(outPath, JSON.stringify(result, null, 2));
  console.log(`Generated ${outPath} with ${Object.keys(result).length} entries.`);
}

console.log("All dictionary packs generated successfully!");
