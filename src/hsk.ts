export interface HskBadgeInfo {
  level: number;
  label: string;
  color: string;
  bg: string;
}

export const HSK_COLORS: Record<number, { color: string; bg: string }> = {
  1: { color: "#10b981", bg: "rgba(16, 185, 129, 0.16)" }, // Green
  2: { color: "#06b6d4", bg: "rgba(6, 182, 212, 0.16)" },  // Cyan
  3: { color: "#3b82f6", bg: "rgba(59, 130, 246, 0.16)" }, // Blue
  4: { color: "#8b5cf6", bg: "rgba(139, 92, 246, 0.16)" }, // Purple
  5: { color: "#f59e0b", bg: "rgba(245, 158, 11, 0.16)" }, // Orange/Gold
  6: { color: "#ef4444", bg: "rgba(239, 68, 68, 0.16)" },  // Red
};

/**
 * Returns the HSK level (1 to 6) of a Chinese word, or null if unlisted
 */
export function getHskLevel(word: string): number | null {
  if (!word) return null;
  const clean = word.trim();
  if (HSK_1_WORDS.has(clean)) return 1;
  if (HSK_2_WORDS.has(clean)) return 2;
  if (HSK_3_WORDS.has(clean)) return 3;
  if (HSK_4_WORDS.has(clean)) return 4;
  if (HSK_5_WORDS.has(clean)) return 5;
  if (HSK_6_WORDS.has(clean)) return 6;

  return null;
}

/**
 * Returns formatted badge information for UI rendering
 */
export function getHskBadgeInfo(word: string): HskBadgeInfo | null {
  const level = getHskLevel(word);
  if (level === null) return null;
  const styling = HSK_COLORS[level] || { color: "#7c3aed", bg: "rgba(124, 58, 237, 0.16)" };
  return {
    level,
    label: `HSK ${level}`,
    color: styling.color,
    bg: styling.bg,
  };
}
