let customRussianDictionary: Record<string, string[]> | null = null;

/**
 * Injects custom or externally loaded Russian dictionary data
 */
export function setCustomRussianDictionary(data: Record<string, string[]>): void {
  customRussianDictionary = data;
}

/**
 * Returns Russian translations for a word if available in БКРС database
 */
export function getRussianDefinitions(word: string): string[] | null {
  if (!word) return null;
  const clean = word.trim();
  if (customRussianDictionary && customRussianDictionary[clean]) {
    return customRussianDictionary[clean];
  }
  return RUSSIAN_TRANSLATIONS[clean] || null;
}

/**
 * Returns raw array of definitions according to user language choice:
 * - "ru": Russian (with English supplement if Russian has few definitions)
 * - "both": Russian + English combined
 * - "en": Standard English CC-CEDICT definitions
 */
export function getRawDefinitionsList(
  word: string,
  englishDefs: string[],
  language: "en" | "ru" | "both" = "ru",
  maxCount: number = 6
): string[] {
  if (language === "en") {
    return englishDefs.slice(0, maxCount);
  }

  const ru = getRussianDefinitions(word);

  if (language === "ru") {
    if (ru && ru.length > 0) {
      if (ru.length < maxCount && englishDefs.length > 0) {
        const combined = [...ru];
        for (const en of englishDefs) {
          if (combined.length >= maxCount) break;
          if (!combined.includes(en)) {
            combined.push(en);
          }
        }
        return combined.slice(0, maxCount);
      }
      return ru.slice(0, maxCount);
    }
    return englishDefs.slice(0, maxCount);
  }

  if (language === "both") {
    if (ru && ru.length > 0) {
      const combined: string[] = [];
      const half = Math.ceil(maxCount / 2);
      ru.slice(0, half).forEach((r) => combined.push(r));
      for (const en of englishDefs) {
        if (combined.length >= maxCount) break;
        if (!combined.includes(en)) combined.push(en);
      }
      return combined.slice(0, maxCount);
    }
    return englishDefs.slice(0, maxCount);
  }

  return englishDefs.slice(0, maxCount);
}

/**
 * Formats localized definitions according to user language choice:
 * - "ru": Russian (with English fallback if word is not yet in Russian database)
 * - "both": Russian + English side-by-side
 * - "en": Standard English CC-CEDICT definitions
 */
export function formatLocalizedDefinitions(
  word: string,
  englishDefs: string[],
  language: "en" | "ru" | "both" = "en",
  maxCount: number = 6
): string {
  if (language === "en") {
    return englishDefs.slice(0, maxCount).join(", ");
  }

  const ru = getRussianDefinitions(word);

  if (language === "ru") {
    if (ru && ru.length > 0) {
      return ru.slice(0, maxCount).join(", ");
    }
    // Seamless fallback to English if not yet in Russian database
    return englishDefs.slice(0, maxCount).join(", ");
  }

  if (language === "both") {
    if (ru && ru.length > 0) {
      const ruPart = ru.slice(0, 3).join(", ");
      const enPart = englishDefs.slice(0, 3).join(", ");
      return `${ruPart} • ${enPart}`;
    }
    return englishDefs.slice(0, maxCount).join(", ");
  }

  return englishDefs.slice(0, maxCount).join(", ");
}
