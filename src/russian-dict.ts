/**
 * Returns Russian definitions for a Chinese word if available
 */
export function getRussianDefinitions(word: string): string[] | null {
  if (!word) return null;
  const clean = word.trim();
  return RUSSIAN_TRANSLATIONS[clean] || null;
}

/**
 * Formats localized definitions according to user language preference:
 * - "en": Standard English definitions
 * - "ru": Russian definitions (with fallback to English if not yet mapped)
 * - "both": Russian primary + English secondary
 */
export function formatLocalizedDefinitions(
  word: string,
  englishDefs: string[],
  language: "en" | "ru" | "both" = "en",
  maxCount: number = 3
): string {
  const ruDefs = getRussianDefinitions(word);

  if (language === "ru") {
    if (ruDefs && ruDefs.length > 0) {
      return ruDefs.slice(0, maxCount).join(", ");
    }
    // Fallback: clean English definitions with indicator
    return englishDefs.slice(0, maxCount).join(", ");
  }

  if (language === "both") {
    if (ruDefs && ruDefs.length > 0) {
      const ruStr = ruDefs.slice(0, 2).join(", ");
      const enStr = englishDefs.slice(0, 2).join(", ");
      return `${ruStr} (${enStr})`;
    }
    return englishDefs.slice(0, maxCount).join(", ");
  }

  // Default: English
  return englishDefs.slice(0, maxCount).join(", ");
}
